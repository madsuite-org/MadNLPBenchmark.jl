# The configuration names, option names and option values of configs.jl, as configs.toml, so
# that a job can be checked without loading Julia.
#
#     julia --project=. configs_toml.jl           # check that configs.toml is up to date
#     julia --project=. configs_toml.jl --write   # rewrite it

using MadNLP, HSL, NLPModels, NLPModelsIpopt, cuMadNLP, SHA, TOML

include(joinpath(@__DIR__, "configs.jl"))

function all_options()
    names = collect(fieldnames(MadNLP.MadNLPOptions))
    for value in values(OPTION_VALUES)
        type = value()
        type isa Type && hasmethod(MadNLP.default_options, Tuple{Type{type}}) || continue
        append!(names, fieldnames(typeof(MadNLP.default_options(type))))
    end
    return unique!(names)
end

function listing()
    names(device; hsl) = first.(configs(device; hsl))
    cpu, cpu_without = names(:cpu; hsl = true), names(:cpu; hsl = false)
    solvers = Dict{String, Any}()
    for (name, value) in OPTION_VALUES
        type = value()
        type isa Type && hasmethod(MadNLP.default_options, Tuple{Type{type}}) || continue
        options = MadNLP.default_options(type)
        options isa MadNLP.AbstractOptions && (solvers[name] = sort!(string.(collect(fieldnames(typeof(options))))))
    end
    return Dict{String, Any}(
        "configurations" => Dict(
            "cpu" => Dict("names" => cpu, "requires_hsl" => setdiff(cpu, cpu_without)),
            "cuda" => Dict("names" => names(:cuda; hsl = false), "requires_hsl" => String[]),
        ),
        "options" => Dict(
            "madnlp" => sort!(string.(collect(fieldnames(MadNLP.MadNLPOptions)))),
            "linear_solver" => solvers,
        ),
        "values" => Dict(
            "names" => sort!(collect(keys(OPTION_VALUES))),
            # options that take a bare word, by declared type
            "word" => sort!([string(n) for n in all_options() if option_type(n) <: AbstractString && !(n in REFUSED_OPTIONS)]),
            "character" => sort!([string(n) for n in all_options() if option_type(n) <: AbstractChar]),
            "refused" => sort!(string.(collect(REFUSED_OPTIONS))),
        ),
    )
end

function main(args)
    path = joinpath(@__DIR__, "configs.toml")
    text = "# Generated by configs_toml.jl from configs.jl; do not edit.\n" * sprint(io -> TOML.print(io, listing(); sorted = true))
    if "--write" in args
        write(path, text)
    elseif !isfile(path) || read(path, String) != text
        error("configs.toml is out of date: run `julia --project=. configs_toml.jl --write`")
    end
    return
end

main(ARGS)
